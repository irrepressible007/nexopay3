#!/usr/bin/env bash
# Create the .env file for this Nexopay install, on the server.
# Secrets are typed hidden and written straight to .env (mode 600): they never
# appear on screen, in shell history, or anywhere else.
#
#     bash ~/nexopay3/deploy/make_env.sh
set -euo pipefail

APP_DIR="${APP_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
ENV_FILE="$APP_DIR/.env"
PY=""
for candidate in /opt/alt/python311/bin/python3 python3 python; do
  if command -v "$candidate" >/dev/null 2>&1 && "$candidate" -c "pass" >/dev/null 2>&1; then
    PY="$(command -v "$candidate")"
    break
  fi
done
[ -n "$PY" ] || { echo "No working Python found."; exit 1; }

if [ -e "$ENV_FILE" ]; then
  echo "A .env already exists at $ENV_FILE."
  echo "To recreate it: mv $ENV_FILE $ENV_FILE.old  and run this again."
  exit 1
fi

ask() {  # ask "Question" default -> prints answer
  local answer
  read -rp "$1 [$2]: " answer
  echo "${answer:-$2}"
}

echo "Nexopay .env setup for $APP_DIR"
echo "Press Enter to accept the value in [brackets]."
echo
DOMAIN="$(ask "Website address (no https://)" "new.nexopay.com.bd")"
DOCROOT="$(ask "Document root folder of that domain" "$HOME/$DOMAIN")"
DB_NAME="$(ask "Database name" "${USER}_nexopay3")"
DB_USER="$(ask "Database user" "${USER}_np3")"
while :; do
  read -rsp "Database password (hidden, from cPanel › MySQL Databases): " DB_PASS; echo
  [ -n "$DB_PASS" ] && break
  echo "The password can't be empty."
done
ADMIN_PATH="$(ask "Secret admin address (letters/numbers/dashes)" "control-room")"
MOCK="$(ask "Offer the fake 'Test payment' method? Only for staging (y/n)" "y")"

if [ "$DOMAIN" = "${DOMAIN#www.}" ]; then
  HOSTS="$DOMAIN,www.$DOMAIN"
  ORIGINS="https://$DOMAIN,https://www.$DOMAIN"
else
  HOSTS="$DOMAIN"
  ORIGINS="https://$DOMAIN"
fi
case "$MOCK" in [yY]*) MOCK=True ;; *) MOCK=False ;; esac
SECRET_KEY="$("$PY" -c 'import secrets; print(secrets.token_urlsafe(50))')"
DB_PASS_URL="$(printf '%s' "$DB_PASS" | "$PY" -c 'import sys, urllib.parse; print(urllib.parse.quote(sys.stdin.read(), safe=""))')"
unset DB_PASS

umask 077
cat > "$ENV_FILE" <<ENV
# Generated by deploy/make_env.sh on $(date '+%Y-%m-%d %H:%M'). Keep this file private (mode 600).
DJANGO_SETTINGS_MODULE=nexopay.settings.production
SECRET_KEY=$SECRET_KEY
DEBUG=False
ALLOWED_HOSTS=$HOSTS
CSRF_TRUSTED_ORIGINS=$ORIGINS
SITE_URL=https://$DOMAIN
ADMIN_URL=${ADMIN_PATH%/}/

DATABASE_URL=mysql://$DB_USER:$DB_PASS_URL@localhost:3306/$DB_NAME

# Apache serves these folders directly (no Python process needed).
STATIC_ROOT=$DOCROOT/static
MEDIA_ROOT=$DOCROOT/media
MEDIA_URL=/media/
CACHE_DIR=$APP_DIR/.cache
LOG_DIR=$APP_DIR/logs

# Email and payment credentials are entered in the admin (stored encrypted), not here.
EMAIL_BACKEND=apps.core.mail.SiteEmailBackend
ALLOW_MOCK_PAYMENTS=$MOCK
ENV
chmod 600 "$ENV_FILE"
mkdir -p "$DOCROOT/static" "$DOCROOT/media" "$APP_DIR/logs" "$APP_DIR/.cache"

echo
echo "✓ Wrote $ENV_FILE (private). Summary, secrets hidden:"
sed -E 's/^(SECRET_KEY)=.*/\1=***/; s#(mysql://[^:]+:)[^@]+@#\1***@#' "$ENV_FILE" | grep -v '^#'
