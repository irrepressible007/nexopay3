#!/usr/bin/env bash
# TEMPORARY bridge: run Nexopay as CGI while the host's LiteSpeed Python
# connector (lswsgi) is missing. Each request starts Python (~1 s per page), so
# use it for staging only. Switch back to the normal Python app when the host
# has installed the connector.
#
#   bash ~/nexopay3/deploy/cgi_bridge.sh on       # needs the Python app STOPPED in cPanel
#   bash ~/nexopay3/deploy/cgi_bridge.sh off      # then START the Python app in cPanel
#   bash ~/nexopay3/deploy/cgi_bridge.sh status
set -euo pipefail

main() {
  local action="${1:-status}"
  APP_DIR="${APP_DIR:-$HOME/nexopay3}"
  APP_NAME="$(basename "$APP_DIR")"
  VENV="${VENV:-$(ls -d "$HOME"/virtualenv/"$APP_NAME"/3.* 2>/dev/null | sort -V | tail -1)}"
  local static_root
  static_root="$(grep -E '^STATIC_ROOT=' "$APP_DIR/.env" | cut -d= -f2- || true)"
  DOCROOT="${DOCROOT:-${static_root%/static}}"
  HTACCESS="$DOCROOT/.htaccess"
  CGI="$DOCROOT/cgi-bin/nexopay.cgi"
  BEGIN="# BEGIN NEXOPAY CGI BRIDGE"
  END="# END NEXOPAY CGI BRIDGE"

  [ -n "$DOCROOT" ] && [ -d "$DOCROOT" ] || { echo "Document root not found (check STATIC_ROOT in $APP_DIR/.env)." >&2; exit 1; }
  [ -x "$VENV/bin/python" ] || { echo "Virtualenv not found at $VENV." >&2; exit 1; }

  case "$action" in
    on)
      if grep -qE '^\s*PassengerAppRoot' "$HTACCESS" 2>/dev/null; then
        echo "The Python app is still running for this domain."
        echo "First: cPanel › Setup Python App › your app › 'Stop app' (NOT Destroy, NOT Save). Then run this again."
        exit 1
      fi
      mkdir -p "$DOCROOT/cgi-bin"
      cat > "$CGI" <<CGI
#!$VENV/bin/python
# Nexopay CGI bridge (temporary) — generated by deploy/cgi_bridge.sh
import os
import sys

sys.path.insert(0, "$APP_DIR")
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "nexopay.settings.production")
os.environ["SCRIPT_NAME"] = ""  # the site lives at /, not /cgi-bin/nexopay.cgi

from wsgiref.handlers import CGIHandler  # noqa: E402

from nexopay.wsgi import application  # noqa: E402

CGIHandler().run(application)
CGI
      chmod 755 "$DOCROOT/cgi-bin" "$CGI"
      cp -p "$HTACCESS" "$HTACCESS.before-cgi-bridge" 2>/dev/null || true
      strip_block
      cat >> "$HTACCESS" <<HT
$BEGIN
<IfModule mod_rewrite.c>
RewriteEngine On
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_URI} !^/cgi-bin/
RewriteRule ^(.*)$ /cgi-bin/nexopay.cgi/\$1 [L,QSA]
</IfModule>
$END
HT
      echo "✓ CGI bridge ON for $DOCROOT"
      ;;
    off)
      strip_block
      rm -f "$CGI"
      echo "✓ CGI bridge OFF. Now: cPanel › Setup Python App › 'Start app'."
      ;;
    status)
      if grep -qF "$BEGIN" "$HTACCESS" 2>/dev/null; then echo "CGI bridge: ON"; else echo "CGI bridge: off"; fi
      if grep -qE '^\s*PassengerAppRoot' "$HTACCESS" 2>/dev/null; then echo "Python app: running"; else echo "Python app: stopped"; fi
      ;;
    *)
      echo "Usage: $0 on|off|status" >&2
      exit 1
      ;;
  esac
}

strip_block() {
  [ -f "$HTACCESS" ] || return 0
  local tmp="$HTACCESS.tmp.$$"
  awk -v b="$BEGIN" -v e="$END" '$0==b{skip=1} !skip{print} $0==e{skip=0}' "$HTACCESS" > "$tmp"
  cat "$tmp" > "$HTACCESS"
  rm -f "$tmp"
}

main "$@"
exit
